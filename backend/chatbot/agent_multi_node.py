def _diag_leak_markers(text: str) -> List[str]:
    """Markers that indicate an internal error / unhandled path leaked to the guest."""
    markers = [
        "Error:", "Failed to", "Traceback", "Exception:", "Technical error",
        "not found for this session", "sqlalchemy", "NoneType",
    ]
    return [m for m in markers if m in (text or "")]


def _diag_inability_markers(text: str) -> List[str]:
    """Phrases that mean the bot is telling the guest it cannot do the thing."""
    markers = [
        "i don't have", "i do not have", "cannot", "can't", "unable to",
        "could not", "couldn't", "not able to", "don't have that information",
        "do not have that information", "no information",
    ]
    lowered = (text or "").lower()
    return [m for m in markers if m in lowered]


