# 3. Node 2: Triage (Classify Intent)
# =============================================================================

def triage_node(state: AgentState) -> AgentState:
    """Classifies user intent into BOOKING, MY_BOOKINGS, PAYMENT_REFUND, SUPPORT, or OTHER."""
    print("\n--- [TRIAGE] Classifying user intent ---")
    text = state.get("sanitized_message", "")
    retry_count = state.get("retry_count", 0)
    human_feedback = state.get("human_feedback", "")
    log = list(state.get("action_log", []))

    # Keyword lists must be defined BEFORE they are used in matching
    payment_refund_keywords = [
        "refund", "refunds", "refunded", "refunding",
        "pay", "paying", "payment", "payments", "paid",
        "checkout link", "check-out link", "pay link", "payment link",
        "billing", "bill", "invoice", "receipt", "charge", "charges", "charged",
        "money back", "reimburse", "reimbursement", "transaction", "fee"
    ]

    booking_keywords = [
        "book", "booking", "booked", "reserve", "reservation",
        "availability", "available", "rooms", "room", "vacant", "vacancy",
        "stay", "check in", "checkin", "check-in", "checkout", "check out", "check-out",
        "dates", "date", "price per night", "deluxe", "executive", "rate", "rates", "cost"
    ]

    my_bookings_keywords = [
        "my booking", "my bookings", "my reservation", "existing booking",
        "cancel", "cancelling", "cancellation", "cancel hold",
        "claim", "find booking", "link booking", "lost booking",
        "status", "booking status", "confirmation code", "hb-"
    ]

    # For keyword matching, use ONLY the original user query (sanitized_message)
    # so feedback text like "also tell price" doesn't confuse the routing.
    # The classifier tool gets the combined text for better context.
    text_lower = text.lower()

    # If looping back with human feedback, give the classifier both for context
    combined_eval_text = f"{text} {human_feedback}".strip() if human_feedback else text

    try:
        analysis = analyze_customer_intent_sentiment_tool.invoke({"message": combined_eval_text})
        intent_raw = analysis.get("intent", "SUPPORT") if isinstance(analysis, dict) else "SUPPORT"
    except Exception as e:
        intent_raw = "SUPPORT"
        logger.warning("TRIAGE classifier raised: %s", e)

    matched_keywords = {
        "booking": [k for k in booking_keywords if k in text_lower],
        "payment_refund": [k for k in payment_refund_keywords if k in text_lower],
        "my_bookings": [k for k in my_bookings_keywords if k in text_lower],
    }
    logger.info(
        "TRIAGE raw_intent=%s retry=%d prior_intent=%s matched=%s text=%r feedback=%r",
        intent_raw, retry_count, state.get("intent", ""),
        {k: v[:4] for k, v in matched_keywords.items() if v},
        text[:140], (human_feedback or "")[:80],
    )

    # If already in a retry/refinement loop from a specialist, maintain that specialist unless user asks for a switch
    prior_intent = state.get("intent", "")
    if retry_count > 0 and prior_intent in ["BOOKING", "MY_BOOKINGS", "PAYMENT_REFUND"]:
        # On retry, STAY with the same specialist unless the feedback explicitly
        # contains strong opposing keywords indicating a different intent
        feedback_lower = (human_feedback or "").lower()
        if prior_intent == "BOOKING" and not any(kw in feedback_lower for kw in ["refund", "pay link", "cancel my"]):
            intent = "BOOKING"
        elif prior_intent == "MY_BOOKINGS" and not any(kw in feedback_lower for kw in ["book a room", "refund"]):
            intent = "MY_BOOKINGS"
        elif prior_intent == "PAYMENT_REFUND" and not any(kw in feedback_lower for kw in ["book a room", "available"]):
            intent = "PAYMENT_REFUND"
        else:
            intent = prior_intent
    # Fresh triage classification (Prioritize BOOKING check-in/out before payment)
    elif intent_raw == "BOOKING" or any(kw in text_lower for kw in booking_keywords):
        intent = "BOOKING"
    elif intent_raw == "REFUND" or any(kw in text_lower for kw in payment_refund_keywords):
        intent = "PAYMENT_REFUND"
    elif intent_raw in ["CANCEL", "CLAIM", "MY_BOOKINGS"] or any(kw in text_lower for kw in my_bookings_keywords):
        intent = "MY_BOOKINGS"
    elif intent_raw == "OTHER":
        intent = "OTHER"
    else:
        intent = "SUPPORT"

    print(f"🏷️ [Triage Decision]: Routing to '{intent}' (Retry: {retry_count})")
    logger.info("TRIAGE final_intent=%s (classifier said %s)", intent, intent_raw)
    log.append(f"Triage classified -> {intent}")

    return {
        "intent": intent,
        "action_log": log
    }


