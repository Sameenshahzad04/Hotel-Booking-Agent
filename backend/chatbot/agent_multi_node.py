# --- A. Booking Agent ---
booking_tools = [search_room_availability_tool, create_booking_hold_tool]
booking_llm = llm.bind_tools(booking_tools)

def booking_agent_node(state: AgentState) -> AgentState:
    """Specialist Agent: Availability check and creating 2-hour holds."""
    print("\n--- [SPECIALIST: BOOKING AGENT] Processing room reservation inquiry ---")
    text = state.get("sanitized_message", "")
    session_id = state.get("session_id", 1)
    history = state.get("messages", [])

    system_msg = SystemMessage(content=(
        "You are the Booking Specialist for Pearl Continental (PC) Hotel Lahore.\n"
        "Follow this exact step-by-step workflow when helping guests with room bookings:\n\n"
        "STAGE 1 - AVAILABILITY INQUIRY & PRESENTATION:\n"
        "- If dates are not provided, ask the guest for check-in and check-out dates (YYYY-MM-DD).\n"
        "- Once dates are known, call search_room_availability_tool to retrieve available room types, rates, bed types, and amenities.\n"
        "- PRESENTATION RULES:\n"
        "  * Always present available room types clearly with: Room Name, Bed Type, Rate (PKR/night), and Key Amenities (e.g. Free Wi-Fi, Central AC, Smart TV, Marble Bath, Safe).\n"
        "  * DO NOT show internal room IDs or numeric database IDs (e.g. 'Room Type ID: 1') to the guest! Keep IDs internal for tool calls only.\n\n"
        "STAGE 2 - GUEST DETAILS COLLECTION (MANDATORY BEFORE BOOKING):\n"
        "- When the guest expresses interest in booking a specific room, you MUST ask the guest for:\n"
        "  1. Their chosen Room Type (e.g. Deluxe King)\n"
        "  2. Their Full Name\n"
        "  3. Their Email Address\n"
        "- CRITICAL RULE: NEVER call create_booking_hold_tool with fake or placeholder values like '[Guest Name]' or '[Guest Email]'.\n"
        "- CRITICAL RULE: NEVER ask the guest for 'session_id' or internal tokens; the system handles that automatically.\n\n"
        "STAGE 3 - CREATING THE HOLD:\n"
        "- ONLY call create_booking_hold_tool when you have real user-provided values for: room_type_id, check_in, check_out, guests, guest_name, and guest_email.\n"
        "- Once the room hold is created, share the confirmation details with the guest (Booking Reference, Room booked, and Hold expiration time).\n"
        f"Active Guest Session ID: {session_id}"
    ))

    convo_input = [system_msg] + (history if history else [HumanMessage(content=text)])

    try:
        # --- LLM CALL #1 (tool request) / LLM CALL #2 (final reply) --------
        # This node is entered TWICE per turn:
        #   1st entry -> model asks for a tool -> graph routes to ToolNode
        #   2nd entry -> history now contains the ToolMessage, so the model
        #                sees the tool output and writes the guest-facing reply.
        ai_msg = booking_llm.invoke(convo_input)
        if ai_msg.tool_calls:
            print(f"🔧 [Booking] LLM requested tools: {[c['name'] for c in ai_msg.tool_calls]}")
        else:
            print("💬 [Booking] LLM produced the final guest-facing reply.")

        # Inject session_id into tool calls for tools that need it
        for call in ai_msg.tool_calls:
            if call["name"] in {"create_booking_hold_tool"}:
                call["args"]["session_id"] = session_id

        # If the model requested tools, the graph routes to the ToolNode which
        # runs them and returns proper ToolMessage objects. The agent is then
        # re-entered and produces the final guest-facing reply.
        result: dict = {"messages": [ai_msg]}
        if not ai_msg.tool_calls:
            result["draft_response"] = ai_msg.content
        return result
    except Exception as e:
        return {"messages": [AIMessage(content=str(e))], "draft_response": str(e)}


