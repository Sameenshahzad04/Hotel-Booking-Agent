def route_triage(state: AgentState) -> str:
    """Routes from triage to the appropriate specialist branch."""
    intent = state.get("intent", "SUPPORT")
    if intent == "BOOKING":
        return "booking_agent"
    elif intent == "MY_BOOKINGS":
        return "my_bookings_agent"
    elif intent == "PAYMENT_REFUND":
        return "payment_refund_agent"
    elif intent == "OTHER":
        return "polite_decline"
    else:
        return "support_agent"

def route_verifier(state: AgentState) -> str:
    """
    Routes from verifier:
    - If human approved: proceed to log_to_ticket -> END
    - If human provided refinement/feedback: loop back to triage with chat history
    """
    passed = state.get("verifier_passed", True)
    retry_count = state.get("retry_count", 0)

    # In human verification, allow the user to refine as much as needed (up to 15 interactive turns)
    if not passed and retry_count < 15:
        print(f"🔄 [Verifier Routing]: Looping back to Triage with chat history (Turn {retry_count})")
        return "triage"

    return "log_to_ticket"


