class AgentState(TypedDict):
    messages: Annotated[List[BaseMessage], add_messages]  # Full conversation memory (all dialogue turns)
    sanitized_message: str        # Output of input_guard
    intent: str                   # BOOKING | MY_BOOKINGS | PAYMENT_REFUND | SUPPORT | OTHER
    session_id: int               # Active guest session ID
    draft_response: str           # Response generated by specialist
    verifier_passed: bool         # Whether human approved
    retry_count: int              # Retry counter for loop back to triage
    human_feedback: str           # Clarification/correction provided by human
    action_log: List[str]         # Audit trail
    crm_ticket_id: str            # Ticket ID created in log_to_ticket


