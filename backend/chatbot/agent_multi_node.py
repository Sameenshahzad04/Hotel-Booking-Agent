def verifier_node(state: AgentState) -> AgentState:
    """
    Customer verification & interaction checkpoint.

    This node acts as the customer's interaction point within the graph:
    - Shows the agent's draft response to the customer.
    - If the customer types ANY text (e.g. "yes book it", "Oct 25-27", "my name is John")
      → treated as continuation feedback → loops back to the specialist.
    - If the customer presses Enter (empty input) on a COMPLETED task
      → approved → goes to log_to_ticket → END.
    - If the task is NOT complete (agent asked a question), even Enter loops back.

    This allows multi-step flows like:
      availability check → room selection → collect details → create booking
    to happen within a single conversation.
    """
    print("\n" + "=" * 60)
    print("🔍 [VERIFIER: CUSTOMER VERIFICATION CHECKPOINT]")
    print("=" * 60)

    # Read draft from the last AIMessage in messages
    messages = state.get("messages", [])
    draft = ""
    for msg in reversed(messages):
        if isinstance(msg, AIMessage):
            draft = msg.content
            break
    if not draft:
        draft = state.get("draft_response", "")
    retry_count = state.get("retry_count", 0)
    log = list(state.get("action_log", []))
    original_sanitized = state.get("sanitized_message", "")

    # --- Malformed response guard ---
    malformed_markers = (
        "<|tool_call_start|>", "<|tool_call_end|>",
        "<tool_calls>", "</tool_calls>", "<|python_tag|>",
    )
    if any(marker in (draft or "") for marker in malformed_markers):
        print("⚠️ [Verifier]: Malformed tool-call markup - auto-regenerating.")
        log.append("Verifier: Rejected malformed tool-call markup.")
        return {
            "messages": [HumanMessage(content=(
                "Your previous response contained raw tool-call markup and was rejected. "
                "Rewrite the response as a clean, plain-text concierge message for the guest. "
                "Do NOT include any tool call syntax, tags, or function names in brackets. "
                "Use only the facts from the tool result."
            ))],
            "verifier_passed": False,
            "human_feedback": "Rewrite in plain text without tool call syntax.",
            "sanitized_message": original_sanitized,
            "retry_count": retry_count + 1,
            "action_log": log
        }

    # --- Detect if the task is COMPLETE ---
    # A task is complete when the specialist has finished the main action
    # (e.g., booking created, payment link sent, refund link sent, info given).
    task_complete_markers = [
        "booking hold successfully created", "booking reference:", "hb-",
        "confirmation code", "checkout portal", "refund portal",
        "successfully re-linked", "cancelled successfully",
        "hold expires at",
    ]
    draft_lower = (draft or "").lower()
    is_task_complete = any(m in draft_lower for m in task_complete_markers)

    # Also check: is the agent asking a question? (not complete)
    is_asking_question = draft.rstrip().endswith("?")

    print(f"\n📋 Agent Response:\n\"{draft}\"\n")
    if is_task_complete:
        print("✅ [Task Status]: COMPLETE - press Enter to approve, or type to continue.")
    elif is_asking_question:
        print("❓ [Task Status]: Agent is asking a question - type your answer.")
    else:
        print("💬 [Task Status]: In progress - type to continue, or press Enter to approve.")

    # --- Get customer input ---
    feedback = ""
    approved = False

    try:
        user_choice = input("👉 Customer: ").strip()

        if user_choice == "":
            # Empty input (just Enter)
            if is_task_complete or (not is_asking_question):
                # Task done or agent gave info → approve
                approved = True
                print("✅ [Verifier]: Response APPROVED.")
                log.append("Verifier: Response approved by customer.")
            else:
                # Agent asked a question → can't approve without answering
                print("⚠️ [Verifier]: Agent asked a question. Please provide an answer.")
                feedback = "The customer pressed Enter without answering. Please ask the question again politely."
                log.append("Verifier: Customer skipped question, re-asking.")
        else:
            # Customer typed something → always treat as continuation
            feedback = user_choice
            approved = False
            print(f"🔄 [Verifier]: Customer replied -> '{feedback}'. Continuing conversation.")
            log.append(f"Verifier: Customer continuation: {feedback}")
    except (EOFError, io.UnsupportedOperation):
        approved = True
        print("✅ [Verifier]: Headless mode - auto-approved.")
        log.append("Verifier: Auto-approved in headless mode.")

    # Build new messages for conversation history
    new_messages: List[BaseMessage] = []
    if not approved and feedback:
        new_messages.append(HumanMessage(content=feedback))

    if approved:
        return {
            "messages": new_messages,
            "draft_response": draft,
            "verifier_passed": True,
            "human_feedback": "",
            "sanitized_message": original_sanitized,
            "retry_count": retry_count,
            "action_log": log
        }
    else:
        return {
            "messages": new_messages,
            "draft_response": draft,
            "verifier_passed": False,
            "human_feedback": feedback,
            "sanitized_message": original_sanitized,
            "retry_count": retry_count + 1,
            "action_log": log
        }


