# 6. Node: Log to Ticket (CRM Logging)
# =============================================================================

def log_to_ticket_node(state: AgentState) -> AgentState:
    """Persists ticket interaction and conversation transcript directly to database Ticket table."""
    print("\n--- [LOG TO TICKET] Logging interaction transcript to CRM Ticket table ---")
    session_id = state.get("session_id", 1)
    intent = state.get("intent", "SUPPORT")
    messages = state.get("messages", [])
    draft = state.get("draft_response", "")

    # Convert conversation messages into JSON serializable format for Ticket.messages column
    # Skip ToolMessages and tool-call-only AIMessages so raw tool output and
    # function-call markup never leak into the CRM transcript.
    transcript = []
    for msg in messages:
        if isinstance(msg, ToolMessage):
            continue
        if isinstance(msg, AIMessage) and getattr(msg, "tool_calls", None):
            continue
        role = "guest" if isinstance(msg, HumanMessage) else "assistant"
        content = msg.content if isinstance(msg.content, str) else str(msg.content)
        if not content.strip():
            continue
        transcript.append({"role": role, "content": content})
    if draft and (not transcript or transcript[-1].get("content") != draft):
        transcript.append({"role": "assistant", "content": draft})

    ticket_id_str = f"TKT-{uuid.uuid4().hex[:8].upper()}"

    # Save to PostgreSQL
    try:
        from models.connection import get_db
        from models.db_models import Ticket, Booking, GuestSession
        db = next(get_db())
        try:
            # Ensure guest session exists in DB
            gs = db.query(GuestSession).filter_by(id=session_id).first()
            if not gs:
                # Provision session row if running in CLI test mode
                gs = GuestSession(id=session_id, session_token_hash=f"cli-token-{session_id}")
                db.add(gs)
                db.commit()

            # Find latest booking associated with this session if any
            latest_booking = (
                db.query(Booking)
                .filter_by(guest_session_id=session_id)
                .order_by(Booking.created_at.desc())
                .first()
            )
            booking_id = latest_booking.id if latest_booking else None

            # Look for the LATEST ticket for this session (any status) to avoid duplicate tickets.
            # Using status="OPEN" here caused a new ticket on every follow-up message,
            # because the first ticket was already flipped to "RESOLVED" once a booking existed.
            existing_ticket = (
                db.query(Ticket)
                .filter_by(guest_session_id=session_id)
                .order_by(Ticket.created_at.desc())
                .first()
            )

            if existing_ticket:
                # APPEND the new transcript so the ticket keeps the full conversation history
                previous_messages = existing_ticket.messages or []
                if isinstance(previous_messages, str):
                    try:
                        previous_messages = json.loads(previous_messages)
                    except Exception:
                        previous_messages = []
                merged = list(previous_messages) + [
                    m for m in transcript if m not in previous_messages
                ]
                existing_ticket.messages = merged
                existing_ticket.category = intent
                if booking_id:
                    existing_ticket.booking_id = booking_id
                    existing_ticket.status = "RESOLVED"
                db.commit()
                ticket_id_str = f"TKT-{existing_ticket.id:05d}"
                print(f"✅ Database Ticket #{existing_ticket.id} UPDATED in PostgreSQL (Category: {intent}, Booking ID: {booking_id})")
            else:
                # Create initial ticket for this conversation
                new_ticket = Ticket(
                    guest_session_id=session_id,
                    booking_id=booking_id,
                    category=intent,
                    status="OPEN" if not booking_id else "RESOLVED",
                    messages=transcript
                )
                db.add(new_ticket)
                db.commit()
                db.refresh(new_ticket)
                ticket_id_str = f"TKT-{new_ticket.id:05d}"
                print(f"✅ Real Database Ticket #{new_ticket.id} CREATED in PostgreSQL (Category: {intent}, Booking ID: {booking_id})")
        finally:
            db.close()
    except Exception as e:
        print(f"⚠️ Warning: Could not write ticket to database: {e}")

    return {"crm_ticket_id": ticket_id_str}


