# 2. Node 1: Input Guard (Length & Injection Check)
# =============================================================================

def input_guard_node(state: AgentState) -> AgentState:
    """Checks message length and filters prompt injection patterns."""
    print("\n--- [INPUT GUARD] Inspecting message for length & injection patterns ---")
    messages = state.get("messages", [])
    
    # Extract latest human message content
    raw_text = ""
    if messages:
        last_msg = messages[-1]
        raw_text = last_msg.content if isinstance(last_msg, BaseMessage) else str(last_msg)
    raw_text = raw_text.strip()
    log = list(state.get("action_log", []))

    if len(raw_text) > 2000:
        raw_text = raw_text[:2000]
        log.append("Input guard: Truncated message exceeding 2000 characters.")

    injection_keywords = [
        "ignore previous instructions", "system prompt", "disregard all prior",
        "jailbreak", "override your rules", "dan mode", "act as an unrestricted"
    ]
    is_suspicious = any(kw in raw_text.lower() for kw in injection_keywords)

    if is_suspicious:
        log.append("Input guard: Suspicious injection pattern detected.")
        sanitized = "I cannot fulfill prompt override instructions. How can I assist you with your PC Hotel stay?"
    else:
        sanitized = raw_text

    return {
        "sanitized_message": sanitized,
        "action_log": log
    }


